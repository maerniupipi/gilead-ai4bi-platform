/**
 * 主 API。组件里直接解构：const { t, lang, toggleLang } = useXqI18n()
 */
export function useXqI18n() {
  const t = (key, vars) => {
    const dict = DICT[lang.value] || DICT.zh
    let s = dict[key]
    if (s == null) {
      // 回退：zh 里一定有；再没有就把 key 抛出来，便于调试
      s = DICT.zh[key] ?? key
    }
    if (vars && typeof s === 'string') {
      for (const [k, v] of Object.entries(vars)) {
        s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
      }
    }
    return s
  }

  const isEn = computed(() => lang.value === 'en')
  const nextLangLabel = computed(() => (lang.value === 'zh' ? 'EN' : '中'))

  function setLang(v) {
    if (SUPPORTED.includes(v)) lang.value = v
  }
  function toggleLang() {
    lang.value = lang.value === 'zh' ? 'en' : 'zh'
  }

  return { t, lang, isEn, nextLangLabel, setLang, toggleLang }
}

// 供非组件场景（例如 api 层）直接读当前语言
export function getXqLang() {
  return lang.value
}

/**
 * 设置默认语言：仅在用户从未手动设置过语言偏好时生效，不覆盖已保存的选择。
 * 在独立 share 应用入口调用，确保首次访问默认显示指定语言。
 */
export function initLang(defaultLang = 'en') {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved && SUPPORTED.includes(saved)) return
  } catch { /* ignore */ }
  if (SUPPORTED.includes(defaultLang)) lang.value = defaultLang
}
