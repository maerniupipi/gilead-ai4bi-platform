def build_schema_prompt(
    *,
    file_name: str = "",
    sheet_name: str = "",
    data_table_name: str = "",
    total_rows: int = 0,
    columns: List[ParsedColumn | dict] | None = None,
    preview_rows: List[list] | None = None,
    understanding_md: Optional[str] = None,
    active_sheets: Optional[List] = None,
) -> str:
    """Assemble schema / samples / business understanding into an LLM-friendly Markdown block.

    Two modes:
    - Multi-sheet: pass ``active_sheets`` (list of objects with file_name, sheet_name,
      data_table_name, columns_json, understanding_md, total_rows).
    - Single-sheet: pass the keyword arguments directly (backward compat).
    """
    if active_sheets and len(active_sheets) > 0:
        return _build_multi_sheet_schema(active_sheets)
    return _build_single_sheet_schema(
        file_name=file_name,
        sheet_name=sheet_name,
        data_table_name=data_table_name,
        total_rows=total_rows,
        columns=columns or [],
        preview_rows=preview_rows,
        understanding_md=understanding_md,
    )


def _build_single_sheet_schema(
    *,
    file_name: str,
    sheet_name: str,
    data_table_name: str,
    total_rows: int,
    columns: List[ParsedColumn | dict],
    preview_rows: List[list] | None = None,
    understanding_md: Optional[str] = None,
) -> str:
    lines: List[str] = []
    if understanding_md and understanding_md.strip():
        lines.append("=== BUSINESS UNDERSTANDING (generated by LLM from sample data — treat as authoritative context) ===")
        lines.append(understanding_md.strip())
        lines.append("=== BUSINESS UNDERSTANDING END ===")
        lines.append("")

    lines.append(f"Source file: {file_name}  (Sheet: {sheet_name})")
    lines.append(f"Physical table name (use this exactly in SQL): `{data_table_name}`")
    lines.append(f"Total rows: {total_rows};  Total columns: {len(columns)}")
    lines.append("")
    lines.append("Column list (column_name = physical name to use in SQL; raw_header = original Excel header for reference only):")
    for c in columns:
        d = _as_dict(c)
        raw    = d.get("raw_header") or ""
        name   = d.get("column_name") or ""
        typ    = d.get("column_type") or "VARCHAR"
        sample = d.get("sample") or []
        sample_show = ", ".join([_fmt(v) for v in sample[:5]])
        lines.append(f"- `{name}`  type:{typ}  original_header:「{raw}」  samples: [{sample_show}]")

    if preview_rows:
        lines.append("")
        lines.append("Data preview (first few rows):")
        lines.append(str(preview_rows[:5]))
    return "\n".join(lines)


def _build_multi_sheet_schema(active_sheets: List) -> str:
    """Build a multi-sheet schema block with numbered sections per sheet.

    Token control: when > 3 active sheets, understanding is truncated to 300 chars
    and sample data is omitted.
    """
    token_control = len(active_sheets) > 3
    blocks: List[str] = []

    for i, s in enumerate(active_sheets, start=1):
        # Support both dataclass and dict
        file_name = getattr(s, "file_name", "") or s.get("file_name", "") if isinstance(s, dict) else getattr(s, "file_name", "")
        sheet_name = getattr(s, "sheet_name", "") or s.get("sheet_name", "") if isinstance(s, dict) else getattr(s, "sheet_name", "")
        data_table_name = getattr(s, "data_table_name", "") or s.get("data_table_name", "") if isinstance(s, dict) else getattr(s, "data_table_name", "")
        columns_json = getattr(s, "columns_json", []) or s.get("columns_json", []) if isinstance(s, dict) else getattr(s, "columns_json", [])
        understanding = getattr(s, "understanding_md", "") or s.get("understanding_md", "") if isinstance(s, dict) else getattr(s, "understanding_md", "")
        total_rows_val = getattr(s, "total_rows", 0) or s.get("total_rows", 0) if isinstance(s, dict) else getattr(s, "total_rows", 0)

        lines: List[str] = []
        lines.append(f"=== SHEET {i}: {file_name} / {sheet_name}  (table: `{data_table_name}`) ===")

        if understanding and understanding.strip():
            ud = understanding.strip()
            if token_control and len(ud) > 300:
                ud = ud[:300] + "…"
            lines.append(f"Understanding: {ud}")

        lines.append(f"Total rows: {total_rows_val};  Columns: {len(columns_json)}")
        lines.append("Columns:")
        for c in columns_json:
            d = _as_dict(c)
            name = d.get("column_name") or ""
            typ = d.get("column_type") or "VARCHAR"
            raw = d.get("raw_header") or ""
            if token_control:
                lines.append(f"- `{name}`  type:{typ}  original_header:「{raw}」")
            else:
                sample = d.get("sample") or []
                sample_show = ", ".join([_fmt(v) for v in sample[:5]])
                lines.append(f"- `{name}`  type:{typ}  original_header:「{raw}」  samples: [{sample_show}]")

        blocks.append("\n".join(lines))

    return "\n\n".join(blocks)


def _as_dict(c: ParsedColumn | dict) -> dict:
    if isinstance(c, dict):
        return c
    return {
        "raw_header": c.raw_header,
        "column_name": c.column_name,
        "column_type": c.column_type,
        "sample": c.sample,
        "distinct": c.distinct,
    }


def _fmt(v) -> str:
    if v is None:
        return "NULL"
    s = str(v)
    if len(s) > 30:
        s = s[:30] + "…"
    return s


