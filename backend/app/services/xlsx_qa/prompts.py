# ---------------------------------------------------------------------------
# Prompt bundle: module-level override → fall back to defaults
# ---------------------------------------------------------------------------

@dataclass
class PromptBundle:
    plan_system: str
    text_to_sql_system: str
    summary_system: str
    chart_system: str
    text_to_sql_retry_system: str   # for SQL retry with error context


_LANG_NAMES: dict[str, str] = {
    "zh": "Simplified Chinese",
    "en": "English",
    "ja": "Japanese",
    "ko": "Korean",
    "fr": "French",
    "de": "German",
    "es": "Spanish",
    "pt": "Portuguese",
    "ar": "Arabic",
    "ru": "Russian",
}


def _build_language_policy(default_language: Optional[str] = None) -> str:
    if not default_language or default_language == "auto" or default_language not in _LANG_NAMES:
        return LANGUAGE_POLICY_AUTO
    lang_display = _LANG_NAMES[default_language]
    return _FIXED_LANGUAGE_POLICY_TMPL.format(lang_display=lang_display)


def _with_language_policy(system: str, default_language: Optional[str] = None) -> str:
    return _build_language_policy(default_language) + system


DEFAULT_PROMPTS = PromptBundle(
    plan_system=_with_language_policy(PLAN_SYSTEM),
    text_to_sql_system=_with_language_policy(TEXT_TO_SQL_SYSTEM),
    summary_system=_with_language_policy(SUMMARY_SYSTEM),
    chart_system=_with_language_policy(CHART_SYSTEM),
    text_to_sql_retry_system=_with_language_policy(TEXT_TO_SQL_RETRY_SYSTEM),
)


def resolve_bundle(
    override: Optional[Mapping[str, Optional[str]]],
    default_language: Optional[str] = None,
) -> PromptBundle:
    ov = override or {}

    def _pick(key: str, default_with_generic_lang: str, base_prompt: str) -> str:
        v = ov.get(key)
        if isinstance(v, str) and v.strip():
            return _with_language_policy(v, default_language)
        if default_language and default_language != "auto" and default_language in _LANG_NAMES:
            return _with_language_policy(base_prompt, default_language)
        return default_with_generic_lang

    return PromptBundle(
        plan_system=_pick("plan_system", DEFAULT_PROMPTS.plan_system, PLAN_SYSTEM),
        text_to_sql_system=_pick("text_to_sql_system", DEFAULT_PROMPTS.text_to_sql_system, TEXT_TO_SQL_SYSTEM),
        summary_system=_pick("summary_system", DEFAULT_PROMPTS.summary_system, SUMMARY_SYSTEM),
        chart_system=_pick("chart_system", DEFAULT_PROMPTS.chart_system, CHART_SYSTEM),
        text_to_sql_retry_system=_pick(
            "text_to_sql_retry_system",
            DEFAULT_PROMPTS.text_to_sql_retry_system,
            TEXT_TO_SQL_RETRY_SYSTEM,
        ),
    )


