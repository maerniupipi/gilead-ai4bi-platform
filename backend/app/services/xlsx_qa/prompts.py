"""
XLSX Smart Q&A · Prompt Templates

Four-stage pipeline prompts (all in English to ensure consistent language detection):
  1. PLAN_SYSTEM        — intent understanding + sub-question decomposition
  2. TEXT_TO_SQL_SYSTEM — single sub-question → one SELECT statement
  3. CHART_SYSTEM       — sub-question results → chart recommendation
  4. SUMMARY_SYSTEM     — all results → business-language report + follow-ups

Additional:
  TEXT_TO_SQL_RETRY_SYSTEM — retry SQL generation with error context
  UNDERSTAND_SYSTEM        — table business-understanding report
  SUGGEST_QUESTIONS_SYSTEM — recommended starter questions
"""
